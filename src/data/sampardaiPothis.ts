function makeManglacharan(seed: PothiSeed): Tuk {
  return {
    id: `${seed.id}-mangal`,
    gurmukhi: seed.manglacharanGurmukhi,
  };
}

function buildPothi(seed: PothiSeed): SampardaiPothi {
  const ardaasTuks: Tuk[] = [
    {
      id: `${seed.id}-ard-1`,
      gurmukhi: seed.ardaasOpening,
    },
    {
      id: `${seed.id}-ard-2`,
      gurmukhi: 'ਪ੍ਰਿਥਮ ਭਗੌਤੀ ਸਿਮਰਿ ਕੈ ਗੁਰ ਨਾਨਕ ਲਈਂ ਧਿਆਇ ॥ ਫਿਰ ਅੰਗਦ ਗੁਰ ਤੇ ਅਮਰਦਾਸੁ ਰਾਮਦਾਸੈ ਹੋਈਂ ਸਹਾਇ ॥',
    },
    {
      id: `${seed.id}-ard-3`,
      gurmukhi: 'ਦਸਾਂ ਪਾਤਸ਼ਾਹੀਆਂ ਦੀ ਜੋਤ ਸ੍ਰੀ ਗੁਰੂ ਗ੍ਰੰਥ ਸਾਹਿਬ ਜੀ ਦੇ ਪਾਠ ਦੀਦਾਰ ਦਾ ਧਿਆਨ ਧਰ ਕੇ ਬੋਲੋ ਜੀ ਵਾਹਿਗੁਰੂ ॥',
    },
    {
      id: `${seed.id}-ard-4`,
      gurmukhi: seed.ardaasUniqueInvocationGurmukhi,
    },
    {
      id: `${seed.id}-ard-5`,
      gurmukhi: seed.ardaasClosingLineGurmukhi,
    },
  ];

  return {
    id: seed.id,
    index: seed.index,
    name: seed.name,
    gurmukhiName: seed.gurmukhiName,
    lineage: seed.lineage,
    region: seed.region,
    maryadaSummary: seed.maryadaSummary,
    manglacharan: makeManglacharan(seed),
    nitnemOrder: seed.nitnemOrder,
    baaniVariants: {
      'chaupai-sahib': {
        openingNote: seed.chaupaiNote,
        extraClosingTuks: [
          {
            id: `${seed.id}-chau-close`,
            gurmukhi: seed.manglacharanGurmukhi,
          },
        ],
      },
      'rehras-sahib': {
        openingNote: seed.rehrasNote,
      },
      'anand-sahib': {
        openingNote: seed.anandNote,
      },
    },
    ardaas: {
      titleGurmukhi: `ਅਰਦਾਸ — ${seed.gurmukhiName}`,
      titleEnglish: `Sampardai Ardaas — ${seed.name}`,
      openingInvocation: seed.ardaasOpening,
      maryadaNote: seed.ardaasMaryadaNote,
      tuks: ardaasTuks,
    },
  };
}

