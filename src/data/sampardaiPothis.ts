import type { SampardaiPothi, Tuk } from '../types/pothi';

interface PothiSeed {
  id: string;
  index: number;
  name: string;
  gurmukhiName: string;
  lineage: string;
  region: string;
  maryadaSummary: string;
  manglacharanGurmukhi: string;
  nitnemOrder: string[];
  chaupaiNote: string;
  rehrasNote: string;
  anandNote: string;
  ardaasOpening: string;
  ardaasMaryadaNote: string;
  ardaasClosingLineGurmukhi: string;
  ardaasUniqueInvocationGurmukhi: string;
}

