function makeManglacharan(seed: PothiSeed): Tuk {
  return {
    id: `${seed.id}-mangal`,
    gurmukhi: seed.manglacharanGurmukhi,
    transliteration: seed.manglacharanTranslit,
    english: seed.manglacharanEnglish,
    teeka: seed.manglacharanTeeka,
    vishraam: [{ wordIndex: 0, type: 'primary' }],
  };
}

